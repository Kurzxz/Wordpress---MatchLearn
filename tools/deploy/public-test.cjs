const { chromium } = require('playwright');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox'],proxy:{server:process.env.HTTPS_PROXY||process.env.HTTP_PROXY}});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('https://matchlearn.cat/?ml-check='+Date.now(),{waitUntil:'networkidle'});
 const essential = page.getByRole('button', {name:/^(Only Essential|Només necessàries|Només essencials)$/}); if(await essential.count()) await essential.click();
 console.log('Title',await page.title(),'H1',await page.locator('h1').first().innerText());
 await page.screenshot({path:'/workspace/matchlearn-tools/deploy/live-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Empresa i societat',exact:true}).click();
 if(await page.locator('.subject-card:visible').count()!==2)throw Error('category filter');
 await page.getByRole('button',{name:'Totes les matèries',exact:true}).click();
 await page.locator('#subject-search').fill('programacio');
 if(await page.locator('.subject-card:visible').count()!==1)throw Error('accent search');
 await page.locator('.subject-card:visible').click();
 await page.locator('#booking-duration').selectOption('2');
 await page.getByRole('button',{name:'Continua al pagament simulat'}).click();
 if(!(await page.locator('#payment-summary').textContent()).includes('24,00'))throw Error('price');
 await page.getByRole('button',{name:'Confirma el pagament fictici'}).click();
 await page.getByRole('button',{name:"Entra a l'aula de mostra"}).click();
 await page.getByRole('button',{name:'Acaba la sessió de mostra'}).click();
 await page.locator('#feedback-form select').selectOption({label:'5 · Ho he entès!'});
 await page.getByRole('button',{name:'Completa la simulació'}).click();
 if(!await page.locator('#feedback-message').isVisible())throw Error('feedback');
 await page.keyboard.press('Escape');
 await page.getByRole('link',{name:'Vull formar-ne part'}).click();
 await page.locator('#tutor-form select').first().selectOption({label:'Ciència i tecnologia'});
 await page.getByRole('button',{name:'Simula la candidatura'}).click();
 if(!await page.locator('#tutor-success').isVisible())throw Error('tutor');
 await page.keyboard.press('Escape');
 await page.locator('#subject-search').fill('');
 await page.setViewportSize({width:390,height:844});
 await page.goto('https://matchlearn.cat/?ml-check='+Date.now(),{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Menú'}).click();
 if(await page.locator('.menu-toggle').getAttribute('aria-expanded')!=='true')throw Error('menu');
 await page.getByRole('link',{name:'Les matèries',exact:true}).click();
 if(await page.locator('.menu-toggle').getAttribute('aria-expanded')!=='false')throw Error('menu close');
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw Error('mobile overflow');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'/workspace/matchlearn-tools/deploy/live-mobile.png',fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: WordPress render, subject filters, accent search, booking, price, simulated payment, classroom, feedback, tutor application, mobile menu, no overflow or JS errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
